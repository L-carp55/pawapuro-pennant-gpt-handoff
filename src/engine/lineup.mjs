// 試合ごとのスタメン9人を決める。
//
// なぜ抽選なのか（T-0094、2026-08-04）:
//   上位9人だけを固定で使うと母集団が実チームとずれる。実チームで上位9人が占めるのは
//   打席の69.7%だけで、残りは打率.205前後の控え・代打が打っている。この不一致が
//   「得点が実測より多く出る」「犠打が出すぎる」という症状になっていた。
//   そこで**全打者を実打席数に比例して起用する**（試合ごとに9人を重み付き抽選）。
//
// ★打順を打席数の多い順に並べてはいけない（2026-08-05に発見して修正）:
//   重み（実打席数）には**すでに打順の効果が入っている**。実際の野球で主力の打席が多いのは、
//   上位打順に置かれているからでもある。それを重みに使ったうえで、さらに打席数順に並べると、
//   主力の打席が二重に増える（開発原則「同じ情報を二重計上しない」に反する）。
//
//   実測（エンジン単体・10シード）: 並べ替えを外すと本塁打の超過が
//     2020 +2.08% → +1.72% ／ 2024 +1.30% → +0.37% ／ 2025 +2.41% → -0.60%
//   年によって0.4〜3.0ポイント下がった。並べ替えが超過の主要因だった。
//
//   打順の見た目（4番に強打者が来る等）は、いまは再現しない。打線の組み方を扱う時に
//   別途設計する——その時は、重みから打順の効果を割り戻さないと同じ二重計上に戻る。

/**
 * 実打席数を重みに、重複なしで9人を抽選する。打順は抽選順のまま（並べ替えない）。
 * @param {Array} roster {weight} を持つ選手の配列
 * @param {Function} rand 0以上1未満を返す乱数
 * @param {number} [size=9] 並べる人数
 */
export function drawLineup(roster, rand, size = 9) {
  const pool = roster.map(p => ({ p, w: p.weight }));
  const picked = [];
  for (let k = 0; k < size && pool.length; k++) {
    let total = 0;
    for (const e of pool) total += e.w;
    let r = rand() * total, idx = pool.length - 1;
    for (let i = 0; i < pool.length; i++) { r -= pool[i].w; if (r <= 0) { idx = i; break; } }
    picked.push(pool[idx].p);
    pool.splice(idx, 1);
  }
  return picked;
}
